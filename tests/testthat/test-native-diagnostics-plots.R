test_that("chain diagnostics use the installed posterior definitions", {
  skip_if_not_installed("posterior")
  a <- array(sin(seq_len(800)*sqrt(2)),c(100,2,4))
  out <- ChainDiagnostics(a,c("a","b","c","d"))
  for(j in 1:4) {
    expect_equal(out$rhat[j],posterior::rhat(a[,,j]))
    expect_equal(out$ess.bulk[j],posterior::ess_bulk(a[,,j]))
    expect_equal(out$ess.tail[j],posterior::ess_tail(a[,,j]))
    expect_equal(out$mcse.mean[j],posterior::mcse_mean(a[,,j]))
  }
  expect_match(attr(out,"backend"),"posterior")
  a[,,1] <- 0
  expect_true(all(is.na(ChainDiagnostics(a)[1,1:4])))
  expect_match(ChainDiagnostics(a)$status[1],"constant")
  expect_true(all(is.na(ChainDiagnostics(a[,1,,drop=FALSE])$rhat)))
  expect_error(ChainDiagnostics(matrix(1,10,4)),"axes")
  expect_error(ChainDiagnostics(array(1,c(3,2,1))),"four")
  d <- gaussian_example();f <- FitRidge(d$X,d$y,10,2,seed=7)
  expect_identical(rownames(ChainDiagnostics(f)),c("beta[a]","beta[b]","intercept","sigma2"))
})

test_that("new result methods preserve numerical selection outputs", {
  X <- diag(2); colnames(X)<-c("a","b"); b<-c(a=2,b=.1)
  sparse <- SAVS(X,b)
  expect_equal(summary(sparse)$selected,c(TRUE,FALSE))
  expect_equal(predict(sparse,X,intercept=1),as.vector(X%*%sparse$coefficients)+1)
  expect_output(print(sparse),"SAVS")
  dss <- DSS(X,b,lambda=1)
  expect_output(print(dss),"DSS")
  expect_equal(predict(dss,X),as.vector(X%*%dss$coefficients))
  z <- SpikeSlabSelection(rbind(c(0,2),c(0,0),c(1,2)))
  expect_equal(summary(z)$inclusion.frequency,c(1/3,2/3))
  expect_equal(summary(z)$MPM,c(FALSE,TRUE))
  expect_output(print(z),"MPM")
  tm <- TwoMeansBeta(rbind(c(.1,2),c(.2,3)),clustering="exact")
  expect_equal(unname(summary(tm)),tm$selected)
  expect_output(print(tm),"Two-means")
  path <- S2MSensitivity(rbind(c(.1,.2,3,4),c(.2,.1,4,3)),c(.1,.5),clustering="exact")
  expect_equal(summary(path)$threshold,path$b.i)
  expect_equal(summary(path)$count,path$H.b.i)
  expect_output(print(path),"threshold")
})

test_that("plots return their numerical values and preserve chain identities", {
  d <- gaussian_example();f<-FitRidge(d$X,d$y,20,2,seed=8)
  file<-tempfile(fileext=".pdf");grDevices::pdf(file)
  on.exit({grDevices::dev.off();unlink(file)},add=TRUE)
  expect_equal(PlotCoefficients(f,selected=1),summary(f))
  expect_equal(PlotTrace(f,"a",xlab="Iteration"),f$beta[,,1])
  skew <- f;skew$beta <- array(0,c(100,1,2));skew$beta[100,1,1] <- 10000
  skew$intercept <- matrix(0,100,1);skew$sigma2 <- matrix(1,100,1)
  PlotCoefficients(skew)
  expect_gte(graphics::par("usr")[2],100)
  ac <- PlotAutocorrelation(f,1,4)
  for(j in 1:2) expect_equal(ac[,j],as.vector(stats::acf(f$beta[,j,1],lag.max=4,plot=FALSE)$acf))
  a <- array(1,c(10,2,1));expect_true(all(is.na(PlotAutocorrelation(a))))
  spike <- FitSpikeSlab(d$X,d$y,10,5,2,seed=1)
  expect_equal(PlotInclusion(spike),SpikeSlabSelection(PosteriorDraws(spike))$inclusion.probability)
  expect_error(PlotInclusion(f),"exact")
  expect_error(PlotTrace(f,0),"variable")
  expect_error(PlotCoefficients(f,selected=3),"indices")
  expect_equal(plot(f,type="trace"),PlotTrace(f))
  path<-S2MSensitivity(rbind(c(.1,.2,3,4),c(.2,.1,4,3)),c(.5,.1),clustering="exact")
  expect_equal(plot(path)$threshold,sort(path$b.i))
})
